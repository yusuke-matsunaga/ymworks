//////////////////////////////////////////////////////////////////////
/// @class EiIOHead  EiIOHead.h "ei/EiIOHead.h"
/// @brief IO のヘッダの基底クラス
//////////////////////////////////////////////////////////////////////
class EiIOHead :
  public ElbIOHead
{
public:

  /// @brief コンストラクタ
  EiIOHead(
    const AstIOHead& ast_header ///< [in] パース木のIO宣言ヘッダ
  );

  /// @brief デストラクタ
  ~EiIOHead();


public:
  //////////////////////////////////////////////////////////////////////
  // ElbIOHead の仮想関数
  //////////////////////////////////////////////////////////////////////

  /// @brief 方向を返す．
  VpiDir
  direction() const override;

  /// @brief 親のモジュールの取得
  const VlModule*
  module() const override;

  /// @brief 親のタスクの取得
  const VlTaskFunc*
  task() const override;

  /// @brief 親の関数の取得
  const VlTaskFunc*
  function() const override;


private:
  //////////////////////////////////////////////////////////////////////
  // データメンバ
  //////////////////////////////////////////////////////////////////////

  // パース木の IO 宣言ヘッダ
  AstIOHead mAstHead;

};


