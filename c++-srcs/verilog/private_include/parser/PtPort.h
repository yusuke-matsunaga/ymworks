//////////////////////////////////////////////////////////////////////
/// @class PtPort PtDecle.h "parser/PtDecl.h"
/// @brief AstPort の実装クラス
///
/// 主な目的は設定用の仮想関数を定義すること．
//////////////////////////////////////////////////////////////////////
class PtPort :
  public AstPort
{
public:
  //////////////////////////////////////////////////////////////////////
  // AstPort の仮想関数
  //////////////////////////////////////////////////////////////////////

  /// @brief 次の要素を返す．
  const AstPort*
  link() const override;


public:
  //////////////////////////////////////////////////////////////////////
  // PtPort の継承クラスが実装する仮想関数
  //////////////////////////////////////////////////////////////////////

  /// @brief 内部のポート結線の向きを設定する．
  virtual
  void
  set_portref_dir(
    SizeType index,
    VpiDir dir
  ) = 0;


public:
  //////////////////////////////////////////////////////////////////////
  // PtPort の関数
  //////////////////////////////////////////////////////////////////////

  /// @brief 次の要素を返す．
  PtPort*
  _link() const
  {
    return mLink;
  }

  /// @brief link を設定する．
  void
  set_link(
    PtPort* link
  )
  {
    mLink = link;
  }


private:
  //////////////////////////////////////////////////////////////////////
  // データメンバ
  //////////////////////////////////////////////////////////////////////

  // 次の要素
  PtPort* mLink{nullptr};

};

/// @brief PtPort のリスト
using PtPortList = PtList<PtPort>;

