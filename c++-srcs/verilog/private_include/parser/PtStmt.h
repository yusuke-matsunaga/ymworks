  link() const override;


public:
  //////////////////////////////////////////////////////////////////////
  // PtStmt の関数
  //////////////////////////////////////////////////////////////////////

  /// @brief 次の要素を返す．
  PtStmt*
  _link() const
  {
    return mLink;
  }

  /// @brief link を設定する．
