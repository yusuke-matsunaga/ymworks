//////////////////////////////////////////////////////////////////////
/// @class EiConstant EiConstant.h "EiConstant.h"
/// @brief 定数を表すクラス
//////////////////////////////////////////////////////////////////////
class EiConstant :
  public EiExprBase
{
protected:

  /// @brief コンストラクタ
  EiConstant(
    const AstExpr& ast_expr ///< [in] パース木の定義要素
  ) : EiExprBase(ast_expr)
  {
  }

  /// @brief デストラクタ
  ~EiConstant() = default;


public:
  //////////////////////////////////////////////////////////////////////
  // VlObj の仮想関数
  //////////////////////////////////////////////////////////////////////

  /// @brief 型の取得
  VpiObjType
  type() const override;


public:
  //////////////////////////////////////////////////////////////////////
  // VlExpr の仮想関数
  //////////////////////////////////////////////////////////////////////

  /// @brief 式のタイプを返す．
  VlExprType
  expr_type() const override;

  /// @brief 定数の時 true を返す．
  bool
  is_const() const override;


public:
  //////////////////////////////////////////////////////////////////////
  // EiExpr の設定用の仮想関数
  //////////////////////////////////////////////////////////////////////

  /// @brief 要求される式の型を計算してセットする．
  void
  _set_reqsize(
    const VlValueType& type ///< [in] 要求される式の型
  ) override;

};


//////////////////////////////////////////////////////////////////////
/// @class EiIntConst EiConstant.h "EiConstant.h"
/// @brief 整数型の定数を表すクラス
//////////////////////////////////////////////////////////////////////
class EiIntConst :
  public EiConstant
{
public:

  /// @brief コンストラクタ
  EiIntConst(
    const AstExpr& ast_expr, ///< [in] パース木の定義要素
    std::int32_t value       ///< [in] 値
  ) : EiConstant(ast_expr),
      mValue{value}
  {
  }

  /// @brief デストラクタ
  ~EiIntConst() = default;


public:
  //////////////////////////////////////////////////////////////////////
  // ElbExpr の仮想関数
  //////////////////////////////////////////////////////////////////////

  /// @brief 式のタイプを返す．
  VlValueType
  value_type() const override;

  /// @brief 定数の型を返す．
  VpiConstType
  constant_type() const override;

  /// @brief 定数値を返す．
  VlValue
  constant_value() const override;


private:
  //////////////////////////////////////////////////////////////////////
  // データメンバ
  //////////////////////////////////////////////////////////////////////

  // 値
  std::int32_t mValue;

};


