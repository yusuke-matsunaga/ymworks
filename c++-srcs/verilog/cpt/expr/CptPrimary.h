// 解説
// もとは generic な一つのクラスだったがメモリ使用量を減らすために
// カスタマイズした．
// 直交した2つの属性で分類している．
// - 階層の有無
// - インデックス/範囲指定の有無, 定数式か否か
// この2つを多重継承で組み合わせると仮想関数テーブルがその数だけ必要に
// なってメモリ節約の意味がなくなるのでかっこ悪さを承知で階層の有無に関
// してはクラスごとに仮想関数を書く．
// また，これらは全ての組合わせがあるわけではないので実際に使われている
// クラスだけ考える．具体的には以下の組み合わせ．
//
//                             simple             hierarchical
// none                          X                     X
// index                                               X
// constant index                X                     X
// range                                               X
// constant range                X
// index and range                                     X
// constant index and range

//////////////////////////////////////////////////////////////////////
// Primary のベース実装クラス
//////////////////////////////////////////////////////////////////////
class CptPrimaryBase :
  public CptExpr
{
public:

  // コンストラクタ
  CptPrimaryBase(
    const char* name
  ) : mName{name}
  {
  }

  // デストラクタ
  ~CptPrimaryBase() {}


public:
  //////////////////////////////////////////////////////////////////////
  // PtExpr の仮想関数
  //////////////////////////////////////////////////////////////////////

  // クラスの型を返す．
  AstExpr::Type
  type() const override;


public:
  //////////////////////////////////////////////////////////////////////
  // PtPrimary の仮想関数
  //////////////////////////////////////////////////////////////////////

  // 末尾の名前を取り出す．
  const char*
  name() const override;

  /// @brief 階層ブランチのリストの先頭を返す．
  const PtNameBranch*
  namebranch_top() const override;

  /// @brief 定数インデックスのチェック
  bool
  is_const_index() const override;

  /// @brief インデックスリストの先頭の取得
  const PtExpr*
  index_top() const override;

  /// @brief 範囲指定を表す構文木を返す．
  /// @return 範囲指定
  const PtPart*
  part() const override;

  // index_list も range も持たないとき true を返す．
  bool
  is_simple() const override;


private:
  //////////////////////////////////////////////////////////////////////
  // データメンバ
  //////////////////////////////////////////////////////////////////////

  // 末尾の名前
  const char* mName;

};


//////////////////////////////////////////////////////////////////////
// Primary のベース実装クラス
//////////////////////////////////////////////////////////////////////
class CptPrimary :
  public CptPrimaryBase
{
public:

  // コンストラクタ
  CptPrimary(
    const FileRegion& file_region,
    const char* name
  ) : CptPrimaryBase(name),
      mFileRegion{file_region}
  {
  }

  // デストラクタ
  ~CptPrimary() {}


public:
  //////////////////////////////////////////////////////////////////////
  // PtExpr の仮想関数
  //////////////////////////////////////////////////////////////////////

  // ファイル位置を返す．
  FileRegion
  file_region() const override;


private:
  //////////////////////////////////////////////////////////////////////
  // データメンバ
  //////////////////////////////////////////////////////////////////////

  // ファイル位置
  FileRegion mFileRegion;

};


