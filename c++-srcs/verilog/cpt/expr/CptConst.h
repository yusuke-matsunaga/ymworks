//////////////////////////////////////////////////////////////////////
// PtConstant のベース実装クラス
//////////////////////////////////////////////////////////////////////
class CptConstant :
  public CptExpr
{
protected:

  // コンストラクタ
  CptConstant(
    const FileRegion& file_region
  ) : mFileRegion{file_region}
  {
  }

  // デストラクタ
  ~CptConstant() {}


public:
  //////////////////////////////////////////////////////////////////////
  // PtExpr の仮想関数
  //////////////////////////////////////////////////////////////////////

  // ファイル位置を返す．
  FileRegion
  file_region() const override;

  // クラスの型を返す．
  // このクラスの場合は kPtConstantExpr を返す．
  AstExpr::Type
  type() const override;


private:
  //////////////////////////////////////////////////////////////////////
  // データメンバ
  //////////////////////////////////////////////////////////////////////

  // ファイル位置
  FileRegion mFileRegion;

};


//////////////////////////////////////////////////////////////////////
// 整数型の定数の基底クラス
//////////////////////////////////////////////////////////////////////
class CptIntConstant :
  public CptConstant
{
public:

  // コンストラクタ
  CptIntConstant(
    const FileRegion& file_region
  ) : CptConstant(file_region)
  {
  }

  // デストラクタ
  ~CptIntConstant() {}


public:
  //////////////////////////////////////////////////////////////////////
  // PtExpr の仮想関数
  //////////////////////////////////////////////////////////////////////

  // 階層名の添字として使える式の時に true を返す．
  bool
  is_index_expr() const override;

  /// @brief インデックスの値の取得
  /// @return 階層名の添字として使える式の時にその値を返す．
  int
  index_value() const override;


public:
  //////////////////////////////////////////////////////////////////////
  // PtConstant の仮想関数
  //////////////////////////////////////////////////////////////////////

  /// @brief 整数型の定数のサイズの取得
  /// @return サイズ
  SizeType
  const_size() const override;

};


//////////////////////////////////////////////////////////////////////
// 整数型の定数(サイズ/基数の指定なし)
//////////////////////////////////////////////////////////////////////
class CptIntConstant1 :
  public CptIntConstant
{
public:

  // コンストラクタ
  CptIntConstant1(
    const FileRegion& file_region,
    SizeType value
  ) : CptIntConstant(file_region),
      mValue{value}
  {
  }

  // デストラクタ
  ~CptIntConstant1() {}


public:
  //////////////////////////////////////////////////////////////////////
  // PtConstant の仮想関数
  //////////////////////////////////////////////////////////////////////

  // 定数の種類を表す型(vpiIntConst, vpiBinaryConst など) を返す．
  VpiConstType
  const_type() const override;

  // ビットベクタ型の値の取得
  BitVector
  const_bitvect() const override;

  // 整数型の文字列の値の取得
  const char*
  const_str() const override;


private:
  //////////////////////////////////////////////////////////////////////
  // データメンバ
  //////////////////////////////////////////////////////////////////////

  // 値
  SizeType mValue;

};


