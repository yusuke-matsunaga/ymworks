//////////////////////////////////////////////////////////////////////
/// @brief 代入文系の基底クラス
//////////////////////////////////////////////////////////////////////
class CptAssignBase :
  public CptStmt
{
protected:

  /// @brief コンストラクタ
  CptAssignBase(
    const FileRegion& file_region,
    const AstExpr* lhs
  ) : CptStmt(file_region),
    mLhs{lhs}
  {
    if ( lhs == nullptr ) {
      throw std::logic_error{"lhs = nullptr"};
    }
  }

  /// @brief デストラクタ
  ~CptAssignBase() {}


public:
  //////////////////////////////////////////////////////////////////////
  // PtStmt の仮想関数
  //////////////////////////////////////////////////////////////////////

  /// @brief lhs を得る．
  const AstExpr*
  lhs() const override;


private:
  //////////////////////////////////////////////////////////////////////
  // データメンバ
  //////////////////////////////////////////////////////////////////////

  // 左辺
  const AstExpr* mLhs;

};


//////////////////////////////////////////////////////////////////////
/// @brief 代入文
//////////////////////////////////////////////////////////////////////
class CptAssign :
  public CptAssignBase
{
public:

  /// @brief コンストラクタ
  CptAssign(
    const FileRegion& file_region,
    const AstExpr* lhs,
    const AstExpr* rhs
  ) : CptAssignBase(file_region, lhs),
      mRhs{rhs}
  {
    if ( rhs == nullptr ) {
      throw std::logic_error{"rhs = nullptr"};
    }
  }

  /// @brief デストラクタ
  ~CptAssign() {}


public:
  //////////////////////////////////////////////////////////////////////
  // PtStmt の派生クラスのための仮想関数
  //////////////////////////////////////////////////////////////////////

  /// @brief クラスの型を返す仮想関数
  Type
  type() const override;

  /// @brief rhs を得る．
  const AstExpr*
  rhs() const override;

  /// @brief コントロールを返す．
  const AstControl*
  control() const override;


private:
  //////////////////////////////////////////////////////////////////////
  // データメンバ
  //////////////////////////////////////////////////////////////////////

  // 右辺
  const AstExpr* mRhs;

};


