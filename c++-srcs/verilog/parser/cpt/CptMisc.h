//////////////////////////////////////////////////////////////////////
/// @brief delay control/event control/repeat control を表すベースクラス
//////////////////////////////////////////////////////////////////////
class CptControl :
  public PtControl
{
protected:

  /// @brief コンストラクタ
  CptControl();

  /// @brief デストラクタ
  ~CptControl();


public:
  //////////////////////////////////////////////////////////////////////
  // PtControl の仮想関数
  //////////////////////////////////////////////////////////////////////

  /// @brief 遅延式の取得
  /// @retval 遅延を表す式 delay control の場合
  /// @retval nullptr 上記以外
  const AstExpr*
  delay() const override;

  /// @brief イベントリストの要素数の取得
  ///
  /// event control/repeat control の場合のみ意味を持つ
  SizeType
  event_num() const override;

  /// @brief イベントリストの要素の取得
  ///
  /// event control/repeat control の場合のみ意味を持つ
  const AstExpr*
  event(
    SizeType pos ///< [in] 位置 ( 0 <= pos < event_num() )
  ) const override;

  /// @brief 繰り返し数の取得
  /// @retval 繰り返し数を表す式 repeat control の場合
  /// @retval nullptr 上記以外
  const AstExpr*
  rep_expr() const override;

};


//////////////////////////////////////////////////////////////////////
/// @brief delay control を表すクラス
//////////////////////////////////////////////////////////////////////
class CptDelayControl :
  public CptControl
{
public:

  /// @brief コンストラクタ
  CptDelayControl(
    const FileRegion& file_region,
    const AstExpr* value
  ) : mTopLoc{file_region.start_loc()},
      mDelay{value}
  {
    if ( value == nullptr ) {
      throw std::logic_error{"value = nullptr"};
    }
  }

  /// @brief デストラクタ
  ~CptDelayControl() {}


public:
  //////////////////////////////////////////////////////////////////////
  // PtControl の仮想関数
  //////////////////////////////////////////////////////////////////////

  /// @brief ファイル位置を返す．
  FileRegion
  file_region() const override;

  /// @brief 型を返す．
  Type
  type() const override;

  /// @brief 遅延式を返す．
  const AstExpr*
  delay() const override;


private:
  //////////////////////////////////////////////////////////////////////
  // データメンバ
  //////////////////////////////////////////////////////////////////////

  // 先頭の位置
  FileLoc mTopLoc;

  // 遅延を表す式
  const AstExpr* mDelay;

};


